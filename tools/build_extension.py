#!/usr/bin/env python3
"""Assemble the Firefox add-on from what is already in this project.

Nothing here is a second implementation of anything. The guide engine, the Cubism
framework, the loader, the point rig and Hu Tao's own files are copied verbatim,
and one generated file is added on top: content.js, the page-side bundle.

Why generated: a content script is a CLASSIC script, in both Firefox and Chrome —
static `import` is simply not available there (only the background worker is a
module). So the five guide modules plus the glue are concatenated in dependency
order with their import/export lines removed, which keeps guide/*.js as the single
source of truth that the demo page also loads.

    python3 tools/build_extension.py [--no-zip]

Outputs build/firefox/ (load that with about:debugging → "Load Temporary Add-on")
and build/hutao-guide-firefox.xpi.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "extension")
OUT = os.path.join(ROOT, "build", "firefox")

# Dependency order. Files here must not import anything outside this list, and
# must not declare the same top-level name as each other — checked below.
BUNDLE = [
    "guide/discovery.js",
    "guide/circularQueue.js",
    "guide/semantics.js",
    "guide/commandRouter.js",
    "guide/paths.js",
    "guide/gazeController.js",
    "guide/live2dBridge.js",
    "guide/index.js",
    "extension/src/content-glue.js",
]

# Copied as plain files: the overlay frame imports them as real ES modules.
COPY_DIRS = ["framework/dist", "framework/shaders", "guide", "live2d", "core"]
COPY_FILES = ["models/manifest.js"]

def rel(*parts):
    return os.path.join(ROOT, *parts)


def read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


# ---------------------------------------------------------------- bundler -----

IMPORT_RE = re.compile(r"^\s*import\b.*\bfrom\s+['\"][^'\"]+['\"];?\s*$")
EXPORT_SET_RE = re.compile(r"^\s*export\s*\{[^}]*\};?\s*$")
EXPORT_DECL_RE = re.compile(r"^(\s*)export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\b)")
TOP_DECL_RE = re.compile(r"^(?:async\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)")


def strip_module_syntax(text, path):
    out = []
    for n, line in enumerate(text.splitlines(), 1):
        if IMPORT_RE.match(line):
            continue
        if EXPORT_SET_RE.match(line):
            continue
        if re.match(r"^\s*import\s*\(", line):
            sys.exit("%s:%d dynamic import() in a bundled file — the bundler "
                     "cannot order it" % (path, n))
        if re.match(r"^\s*export\s+default\b", line):
            sys.exit("%s:%d `default` export is not supported by this bundler" % (path, n))
        # Anything else that starts a module statement is a form this bundler has
        # no rule for; failing here beats shipping a script that throws on load.
        stripped = EXPORT_DECL_RE.sub(r"\1", line)
        # Anything still starting a module statement is a form this bundler has no
        # rule for; failing here beats shipping a script that throws on load.
        if re.match(r"^\s*(?:import|export)\b", stripped):
            sys.exit("%s:%d unhandled module statement: %s" % (path, n, line.strip()))
        out.append(stripped)
    return "\n".join(out)


def top_level_names(text):
    names = []
    for line in text.splitlines():
        m = TOP_DECL_RE.match(line)
        if m:
            names.append(m.group(1))
    return names


def build_bundle():
    chunks, owner = [], {}
    for path in BUNDLE:
        body = strip_module_syntax(read(rel(*path.split("/"))), path)
        for name in top_level_names(body):
            if name in owner:
                sys.exit("Bundling would collide: `%s` is declared at top level in "
                         "both %s and %s" % (name, owner[name], path))
            owner[name] = path
        chunks.append("/* ---- %s ---- */\n%s" % (path, body.strip()))
    joined = "\n\n".join(chunks)
    return (
        "// GENERATED by tools/build_extension.py — do not edit.\n"
        "// The guide engine, verbatim from guide/*.js, plus the page-side glue, in\n"
        "// one classic script: a content script has no import, in Firefox or Chrome.\n"
        "'use strict';\n(function () {\n"
        + joined
        + "\n})();\n"
    )


# ------------------------------------------------------------- assets --------

def hutao_block(text):
    """The hutao entry of models/manifest.js, as text.

    A regex instead of a parser: this is a plain registry literal, and the next
    key at two-space indent is a hard end to the entry. Lines nested inside it are
    indented deeper, so the slice cannot run into the next model.
    """
    start = re.search(r"(?m)^\s{2}hutao:", text)
    if not start:
        sys.exit("Could not find the hutao entry in models/manifest.js")
    tail = text[start.end():]
    nxt = re.search(r"(?m)^\s{2}[A-Za-z_]\w*:", tail)
    return text[start.start():start.end() + (nxt.start() if nxt else len(tail))]


def hutao_files():
    """Everything Hu Tao needs to render, and only that.

    The imported model folder is ~140 MB because it carries both the vendor's
    8K PNG atlases and 2K ones; the page loads the display-sized .webp that
    tools/make_webp.py wrote beside each declared texture, so the add-on ships
    those and leaves the PNGs behind.
    """
    files = set()
    entries = []

    body = hutao_block(read(rel("models", "manifest.js")))

    model3 = re.search(r"model3:\s*'(\./[^']+)'", body)
    if not model3:
        sys.exit("No model3 path in the hutao entry")
    folder = os.path.normpath(os.path.dirname(model3.group(1)))
    entries.append(re.sub(r"^\./", "", model3.group(1)))

    for expr in re.findall(r"file:\s*'([^']+)'", body):
        files.add(folder + "/" + expr)
    # The companions' own model3.json paths (the first model3 match is she herself).
    entries.extend(re.sub(r"^\./", "", p)
                   for p in re.findall(r"model3:\s*'(\./models/[^']+)'", body))

    for path in entries:
        d = os.path.dirname(path)
        files.add(path)
        with open(rel(d, os.path.basename(path)), "r", encoding="utf-8") as f:
            setting = json.load(f)
        fr = setting.get("FileReferences", {})
        for key in ("Moc", "Physics", "Pose", "DisplayInfo"):
            if fr.get(key):
                files.add(d + "/" + fr[key])
        tex = fr.get("Textures") or []
        if isinstance(tex, str):
            tex = [tex]
        for t in tex:
            webp = os.path.join(d, re.sub(r"\.(png|jpe?g)$", ".webp", t, flags=re.I))
            if not os.path.exists(rel(webp)):
                sys.exit("%s is missing — run tools/make_webp.py first, the add-on\n"
                         "does not ship the vendor PNGs." % webp)
            files.add(webp)
    return sorted(files)


def icons():
    """Icon.png is the asset's own art; the toolbar needs 48 and 96."""
    src = rel("models", "hu_tao", "Icon.png")
    out = os.path.join(OUT, "icons")
    os.makedirs(out, exist_ok=True)
    made = []
    for size in (48, 96):
        dst = os.path.join(out, "icon%d.png" % size)
        try:
            subprocess.run(["convert", src, "-resize", "%dx%d" % (size, size), dst],
                           check=True, capture_output=True)
            made.append(dst)
        except (OSError, subprocess.CalledProcessError) as err:
            print("  ! icon%d could not be made (%s); copying the original" % (size, err))
            shutil.copy2(src, dst)
            made.append(dst)
    return made


def copy_tree(sub):
    a, b = rel(sub), os.path.join(OUT, sub)
    # Docs and the folders that hold pages she must not ship with (the guide's own
    # embed demo, the test fixture) stay in the repository, not in the package.
    ignore = shutil.ignore_patterns("embed-demo", "_test", "*.md")
    if os.path.isdir(a):
        shutil.copytree(a, b, dirs_exist_ok=True, ignore=ignore)
    elif os.path.isfile(a):
        os.makedirs(os.path.dirname(b), exist_ok=True)
        shutil.copy2(a, b)
    else:
        sys.exit("Nothing to copy at %s — the add-on cannot work without it" % sub)


# ----------------------------------------------------------------- main ------

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-zip", action="store_true", help="skip the .xpi")
    args = ap.parse_args()

    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)

    print("Bundling the page-side script…")
    write(os.path.join(OUT, "content.js"), build_bundle())

    print("Copying the SDK, the modules and the manifest…")
    for sub in COPY_DIRS:
        copy_tree(sub)
    for sub in COPY_FILES:
        copy_tree(sub)

    print("Copying Hu Tao (webp textures only)…")
    n = 0
    for f in hutao_files():
        dst = os.path.join(OUT, f)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(rel(f), dst)
        n += 1
    print("  %d model file(s)" % n)

    print("Copying the add-on's own files…")
    for name in ("manifest.json", "hutao.html", "panel.html", "action.html"):
        shutil.copy2(os.path.join(SRC, name), os.path.join(OUT, name))
    for name in ("overlay.js", "panel.js", "action.js", "background.js"):
        shutil.copy2(os.path.join(SRC, "src", name), os.path.join(OUT, name))
    icons()

    # The harness: a messy fixture page that loads ../content.js as a classic
    # script, exactly as the manifest does. It is how the whole page-side stack is
    # checked without a browser that can install an add-on, so it ships in the
    # folder but stays out of the .xpi.
    fixture = os.path.join(SRC, "test")
    if os.path.isdir(fixture):
        shutil.copytree(fixture, os.path.join(OUT, "_test"), dirs_exist_ok=True)

    total = sum(os.path.getsize(os.path.join(dp, fn))
                for dp, _, fs in os.walk(OUT) for fn in fs)
    print("build/firefox is ready — %.1f MB" % (total / 1e6))

    if args.no_zip:
        return

    xpi = os.path.join(ROOT, "build", "hutao-guide-firefox.xpi")
    with zipfile.ZipFile(xpi, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for dp, _, fs in os.walk(OUT):
            for fn in fs:
                full = os.path.join(dp, fn)
                arc = os.path.relpath(full, OUT).replace(os.sep, "/")
                if arc.startswith("_test/"):
                    continue
                z.write(full, arc)
    print("Packed %s — %.1f MB" % (os.path.relpath(xpi, ROOT), os.path.getsize(xpi) / 1e6))


if __name__ == "__main__":
    main()
